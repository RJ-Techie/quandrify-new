async function main() {
  console.log('Cleaning database...');
  await prisma.dailySpot.deleteMany();
  await prisma.dailySpotPool.deleteMany();
  await prisma.payment.deleteMany();
  await prisma.contactMessage.deleteMany();
  await prisma.listing.deleteMany();
  await prisma.adminUser.deleteMany();

  const todayStr = getTodayDateString();
  console.log(`Setting up DailySpotPool for ${todayStr}...`);
  
  // Create Today's Spot Pool: 7 claimed, 3 remaining
  await prisma.dailySpotPool.create({
    data: {
      date: todayStr,
      claimedSlots: 7,
      maxSlots: 10,
      isSoldOut: false,
    }
  });

  console.log('Seeding listings...');
  const createdListings = [];

  for (const item of mockListings) {
    const slug = item.title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)+/g, '');
    
    const token = crypto.randomBytes(24).toString('hex');
    const tokenHash = crypto.createHash('sha256').update(token).digest('hex');

    const created = await prisma.listing.create({
      data: {
        slug: `${slug}-${Math.floor(Math.random() * 8999 + 1000)}`,
        title: item.title,
        tagline: item.tagline,
        shortDescription: item.shortDescription,
        fullDescription: item.fullDescription,
        websiteUrl: item.websiteUrl,
        logoUrl: item.logoUrl,
        primaryCtaText: item.primaryCtaText,
        category: item.category,
        companyName: item.companyName,
        founderName: item.founderName,
        foundedDate: item.foundedDate,
        country: item.country,
        city: item.city,
        teamSize: item.teamSize,
        companyStage: item.companyStage,
        revenueModel: item.revenueModel,
        mrr: item.mrr,
        arr: item.arr,
        usersCount: item.usersCount,
        mauCount: item.mauCount,
        customersCount: item.customersCount,
        payingCustomersCount: item.payingCustomersCount,
        growthRate: item.growthRate,
        publicMetricsJson: item.publicMetricsJson || '[]',
        techFrontend: item.techFrontend,
        techBackend: item.techBackend,
        techDatabase: item.techDatabase,
        techCloud: item.techCloud,
        techAi: item.techAi,
        techPayment: item.techPayment,
        linkWebsite: item.linkWebsite,
        linkX: item.linkX,
        linkLinkedIn: item.linkLinkedIn,
        linkGitHub: item.linkGitHub,
        linkProductHunt: item.linkProductHunt,
        founderStoryWhy: item.founderStoryWhy,
        founderStoryProblem: item.founderStoryProblem,
        founderStoryNext: item.founderStoryNext,
        contactName: item.contactName,
        contactEmail: item.contactEmail,
        status: item.status,
        isFeatured: item.isFeatured || false,
        managementToken: token,
        managementTokenHash: tokenHash,
        publishedAt: new Date(),
        viewCount: Math.floor(Math.random() * 2500 + 300),
        clickCount: Math.floor(Math.random() * 400 + 50),
        contactCount: Math.floor(Math.random() * 20 + 2),
        top10Impressions: Math.floor(Math.random() * 5000 + 1000),
      }
    });

    createdListings.push(created);
  }

  console.log(`Created ${createdListings.length} listings.`);

  for (let pos=1;pos<=7;pos++) {
    await prisma.payment.create({data:{listingId:createdListings[pos-1].id,amount:(8-pos)*1000,promotionalAmount:(8-pos)*1000,originalPromotionalAmount:(8-pos)*1000,currency:'usd',hasTop10Addon:true,status:'SUCCEEDED',fulfillmentStatus:'FULFILLED',paidAt:new Date()}});
  }
}
main().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>prisma.$disconnect());
